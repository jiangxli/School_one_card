CREATE TABLE IF NOT EXISTS campus_card (
 user_id BIGINT PRIMARY KEY, card_no VARCHAR(34) NOT NULL UNIQUE,
 write_count INT NOT NULL DEFAULT 0, last_written_at DATETIME NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS campus_card_write (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,user_id BIGINT NOT NULL,
 card_no VARCHAR(34) NOT NULL,request_key VARCHAR(36) NOT NULL UNIQUE,
 operator_id BIGINT NOT NULL, written_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 payload VARCHAR(200) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
